/// One member of a load-balance node as the operator declares it. `slot` is the
/// member's stable number: its port is `member_<slot>`, so a rename or a
/// reorder keeps the bundle drawn on it; `name` is what the operator calls it.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LoadBalanceMember {
    pub slot: u32,
    pub name: String,
}

impl LoadBalanceMember {
    pub fn port_key(&self) -> String {
        format!("{MEMBER_PREFIX}{}", self.slot)
    }
}

/// The key prefix of a member port; the rest is the member's slot.
pub const MEMBER_PREFIX: &str = "member_";

/// The operator's rule: `members` are the bundles this node splits into, one
/// bundle port each, in the order given. `protocol` is how the channels bundled
/// out are relayed to the universal pods they land on. A lane node (generated by
/// the expansion) has no members here: its ports are thin and counted.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LoadBalanceDistributeConfig {
    pub mode: LoadBalanceMode,
    #[serde(default)]
    pub protocol: RelayProtocol,
    #[serde(default)]
    pub members: Vec<LoadBalanceMember>,
}

/// `members` are the bundles this node joins, one bundle port each.
#[derive(Debug, Clone, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct LoadBalanceAggregateConfig {
    #[serde(default)]
    pub members: Vec<LoadBalanceMember>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum LoadBalanceMode {
    RoundRobin,
    Random,
    IpHash,
    Fallback,
}

impl From<LoadBalanceMode> for guru_worker_config::LoadBalanceStrategy {
    fn from(value: LoadBalanceMode) -> Self {
        match value {
            LoadBalanceMode::RoundRobin => guru_worker_config::LoadBalanceStrategy::RoundRobin,
            LoadBalanceMode::Random => guru_worker_config::LoadBalanceStrategy::Random,
            LoadBalanceMode::IpHash => guru_worker_config::LoadBalanceStrategy::IpHash,
            LoadBalanceMode::Fallback => guru_worker_config::LoadBalanceStrategy::Fallback,
        }
    }
}

