/// Updates a node's editable metadata.
///
/// `position` is only written when it is `Some`, so an edit that leaves the
/// position out does not move the node. Whether the edit renamed the node is
/// decided inside the transaction, which is also where the canvas generation is
/// bumped, so a concurrent metadata write cannot land a rename without it.
pub struct UpdateNodeMetaRow {
    pub id: NodeId,
    pub canvas: CanvasId,
    pub name: String,
    pub comment: String,
    pub position: Option<CanvasUiPosition>,
    pub import_sync: Option<ImportSync>,
    /// The snapshot an export Y-move's `import_sync` was computed from; fences
    /// the mirrored-port reshape so a concurrent export edit is not erased by a
    /// stale list. `None` for renames/moves that carry no reshape.
    pub fence: Option<CanvasFence>,
}

/// A node after a metadata update, plus whether the name actually changed.
#[derive(Debug, Clone)]
pub struct NodeMetaUpdated {
    pub renamed: bool,
    pub node: NodeEntity,
    pub ports: Vec<PortEntity>,
}

impl Processor<UpdateNodeMetaRow> for Db {
    type Output = NodeMetaUpdated;
    type Error = Error;
    #[tracing::instrument(name = "Query-Transaction:UpdateNodeMetaRow", skip_all, err, fields(id = %input.id))]
    async fn process(&self, input: UpdateNodeMetaRow) -> Result<Self::Output, Self::Error> {
        // The node name is the forwarding tag in the derived worker config, so a
        // rename has to schedule a derivation; a move or a comment edit is
        // invisible to workers and leaves the generation alone. The old name is
        // read under a row lock inside this transaction rather than by the
        // caller, so a metadata write that started before a concurrent rename
        // cannot overwrite that rename without bumping.
        let mut tx = self.db().begin().await?;
        let previous: String =
            sqlx::query_scalar("SELECT name FROM orchestration_node WHERE id = $1 FOR UPDATE")
                .bind(&input.id)
                .fetch_one(&mut *tx)
                .await?;
        let renamed = previous != input.name;
        sqlx::query("UPDATE orchestration_node SET name = $2, comment = $3 WHERE id = $1")
            .bind(&input.id)
            .bind(&input.name)
            .bind(&input.comment)
            .execute(&mut *tx)
            .await?;
        if let Some(position) = input.position {
            sqlx::query(
                "UPDATE orchestration_node SET position_x = $2, position_y = $3 WHERE id = $1",
            )
            .bind(&input.id)
            .bind(position.x)
            .bind(position.y)
            .execute(&mut *tx)
            .await?;
        }
        // Moving an export node on the y axis renumbers the mirrored ports on the
        // node importing its canvas; that is a UI-only change too, but the list
        // was computed from a snapshot, so it is fenced: a concurrent export
        // edit that added a mirrored port cannot be erased by a stale list.
        if let Some(sync) = &input.import_sync {
            reshape_ports(&mut tx, &sync.node, &sync.ports).await?;
            fence::touch_checked(&mut tx, &input.canvas, input.fence.as_ref()).await?;
        } else if renamed {
            fence::touch(&mut tx, &input.canvas).await?;
        }
        let node = node_by_id(&mut tx, &input.id)
            .await?
            .ok_or(Error::Query(sqlx::Error::RowNotFound))?;
        let ports = ports_of(&mut tx, &input.id).await?;
        tx.commit().await?;
        Ok(NodeMetaUpdated {
            renamed,
            node,
            ports,
        })
    }
}

/// Rewrites a node's spec and reshapes its ports in place.
///
/// A port whose key survives keeps its row id, so the edges attached to it stay
/// attached; ports whose key disappears are deleted with their edges (the service
/// refuses the edit before that can happen silently).
pub struct UpdateNodeSpecRow {
    pub id: NodeId,
    pub canvas: CanvasId,
    pub spec: NodeSpec,
    pub ports: Vec<NewPort>,
    pub import_sync: Option<ImportSync>,
    /// The snapshot the edit was validated against, fencing the write.
    pub fence: Option<CanvasFence>,
}

impl Processor<UpdateNodeSpecRow> for Db {
    type Output = NodeWithPorts;
    type Error = Error;
    #[tracing::instrument(name = "Query-Transaction:UpdateNodeSpecRow", skip_all, err, fields(id = %input.id))]
    async fn process(&self, input: UpdateNodeSpecRow) -> Result<Self::Output, Self::Error> {
        let mut tx = self.db().begin().await?;
        write_spec(&mut tx, &input.id, &input.spec).await?;
        reshape_ports(&mut tx, &input.id, &input.ports).await?;
        if let Some(sync) = &input.import_sync {
            reshape_ports(&mut tx, &sync.node, &sync.ports).await?;
        }
        fence::touch_checked(&mut tx, &input.canvas, input.fence.as_ref()).await?;
        let node = node_by_id(&mut tx, &input.id)
            .await?
            .ok_or(Error::Query(sqlx::Error::RowNotFound))?;
        let ports = ports_of(&mut tx, &input.id).await?;
        tx.commit().await?;
        Ok(NodeWithPorts { node, ports })
    }
}

#[derive(Debug)]
pub struct DeleteNodeRow {
    pub id: NodeId,
    pub canvas: CanvasId,
    pub import_sync: Option<ImportSync>,
    /// The canvas this node stops importing (set when it is an import node): it
    /// becomes a root again and gets its own generation bump.
    pub frees_canvas: Option<CanvasId>,
    /// The snapshot the delete was validated against; `None` bumps
    /// unconditionally (an Admin force delete).
    pub fence: Option<CanvasFence>,
}

impl Processor<DeleteNodeRow> for Db {
    type Output = ();
    type Error = Error;
    #[tracing::instrument(name = "Query-Transaction:DeleteNodeRow", skip_all, err)]
    async fn process(&self, input: DeleteNodeRow) -> Result<Self::Output, Self::Error> {
        let mut tx = self.db().begin().await?;
        // Ports, their edges, the node's health history and its relay leaf all
        // cascade from the row.
        sqlx::query("DELETE FROM orchestration_node WHERE id = $1")
            .bind(&input.id)
            .execute(&mut *tx)
            .await?;
        // Retiring an export node drops its mirrored port (and that port's edge)
        // on the importing node.
        if let Some(sync) = &input.import_sync {
            reshape_ports(&mut tx, &sync.node, &sync.ports).await?;
        }
        fence::touch_checked(&mut tx, &input.canvas, input.fence.as_ref()).await?;
        // Retiring an import node makes its target a root again, with a
        // derivation pass of its own to run.
        if let Some(freed) = &input.frees_canvas {
            sqlx::query(
                "UPDATE orchestration_canvas SET generation = generation + 1 WHERE id = $1",
            )
            .bind(freed)
            .execute(&mut *tx)
            .await?;
        }
        tx.commit().await?;
        Ok(())
    }
}

/// The distinct canvases the given nodes belong to; the relay leaf rotation
/// cron re-derives these after re-issuing.
#[derive(Debug)]
pub struct ListCanvasesOfNodes {
    pub nodes: Vec<NodeId>,
}

impl Processor<ListCanvasesOfNodes> for Db {
    type Output = Vec<CanvasId>;
    type Error = Error;
    #[tracing::instrument(name = "Query:ListCanvasesOfNodes", skip_all, err)]
    async fn process(&self, input: ListCanvasesOfNodes) -> Result<Self::Output, Self::Error> {
        if input.nodes.is_empty() {
            return Ok(Vec::new());
        }
        Ok(sqlx::query_scalar(
            "SELECT DISTINCT canvas FROM orchestration_node WHERE id = ANY($1) ORDER BY canvas",
        )
        .bind(&input.nodes)
        .fetch_all(self.db())
        .await?)
    }
}

/// The root canvases of every tree holding a TLS or QUIC relay: the trees whose
/// derivation depends on the internal CA. `InitInternalCa` touches them so pods
/// reported invalid for lack of a CA get their first leaves.
#[derive(Debug)]
pub struct ListCanvasesWithRelayTls;

impl Processor<ListCanvasesWithRelayTls> for Db {
    type Output = Vec<CanvasId>;
    type Error = Error;
    #[tracing::instrument(name = "Query:ListCanvasesWithRelayTls", skip_all, err)]
    async fn process(&self, _: ListCanvasesWithRelayTls) -> Result<Self::Output, Self::Error> {
        let mut conn = self.db().acquire().await?;
        let canvases: Vec<CanvasId> = sqlx::query_scalar(
            "SELECT DISTINCT canvas FROM orchestration_node
             WHERE spec ->> 'type' = 'relay'
               AND spec -> 'config' ->> 'protocol' IN ('tcp_tls', 'quic')",
        )
        .fetch_all(&mut *conn)
        .await?;
        let mut roots = Vec::with_capacity(canvases.len());
        for canvas in &canvases {
            roots.push(tree::root_of(&mut conn, canvas).await?);
        }
        roots.sort();
        roots.dedup();
        Ok(roots)
    }
}
