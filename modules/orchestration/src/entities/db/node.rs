/// A port to create together with its node.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NewPort {
    pub kind: PortKind,
    pub direction: PortDirection,
    pub key: String,
    pub position: i64,
}

/// The importing node whose derived ports must follow this edit, and the port
/// set it must end up with. `None` when the edited node is not an export node
/// of an imported canvas.
///
/// Applied by [`crate::entities::db::port::reshape_ports`] in the same transaction
/// as the export edit: a mirrored port whose key survives keeps its row and edges.
#[derive(Debug, Clone)]
pub struct ImportSync {
    pub node: NodeId,
    pub ports: Vec<NewPort>,
}

/// The key `import_sync.ports` uses for the export node being created, whose id
/// only exists inside the transaction; `CreateNodeRow` substitutes the real one
/// after the insert.
pub const PENDING_EXPORT_KEY: &str = "pending-node";

pub struct CreateNodeRow {
    pub canvas: CanvasId,
    pub name: String,
    pub comment: String,
    pub spec: NodeSpec,
    pub position: CanvasUiPosition,
    pub ports: Vec<NewPort>,
    pub import_sync: Option<ImportSync>,
    /// The importer tree the create was validated against, fencing the write;
    /// `None` bumps unconditionally (a snapshotless create, e.g. a server's
    /// universal pod).
    pub fence: Option<CanvasFence>,
    /// For an import node, the target tree — a second, independent root loaded
    /// and validated alongside the importer — claimed in the same transaction so
    /// a concurrent edit to the target rolls the import back. Only its generation
    /// is used; the target root is the import's `spec.config.canvas`.
    pub target_fence: Option<CanvasFence>,
}

impl Processor<CreateNodeRow> for Db {
    type Output = NodeWithPorts;
    type Error = Error;
    #[tracing::instrument(
        name = "Query-Transaction:CreateNodeRow",
        skip_all,
        err,
        fields(
            canvas = %input.canvas,
            name = ?input.name,
        )
    )]
    async fn process(&self, input: CreateNodeRow) -> Result<Self::Output, Self::Error> {
        let mut tx = self.db().begin().await?;
        if let NodeSpec::CanvasImport(cfg) = &input.spec {
            let mut chain = tree::ancestors_of(&mut tx, &input.canvas).await?;
            chain.push(input.canvas.clone());
            if chain.contains(&cfg.canvas) {
                return Err(Error::Conflict(IMPORT_CYCLE));
            }
            // "Already imported" is the UNIQUE constraint on `import_canvas`,
            // named by `insert_node`.
        }
        let node = insert_node(
            &mut tx,
            &input.canvas,
            &input.name,
            &input.comment,
            &input.spec,
            input.position,
            None,
        )
        .await?;
        let ports = insert_ports(&mut tx, &node.id, &input.ports).await?;
        // The target stops being a root: its own pending derivation collapses
        // into this tree's. Writing its row also makes two concurrent imports of
        // each other contend instead of forming a cycle.
        if let NodeSpec::CanvasImport(cfg) = &input.spec {
            match &input.target_fence {
                None => {
                    sqlx::query(
                        "UPDATE orchestration_canvas SET derived_generation = generation WHERE id = $1",
                    )
                    .bind(&cfg.canvas)
                    .execute(&mut *tx)
                    .await?;
                }
                Some(target) => fence::claim_root(&mut tx, &cfg.canvas, target.generation).await?,
            }
        }
        // An export node's mirrored port on the importer is keyed by the export's
        // id, which only exists now: swap the placeholder for it.
        if let Some(sync) = &input.import_sync {
            let synced: Vec<NewPort> = sync
                .ports
                .iter()
                .map(|p| {
                    if p.key == PENDING_EXPORT_KEY {
                        NewPort {
                            key: node.id.to_string(),
                            ..p.clone()
                        }
                    } else {
                        p.clone()
                    }
                })
                .collect();
            reshape_ports(&mut tx, &sync.node, &synced).await?;
        }
        fence::touch_checked(&mut tx, &input.canvas, input.fence.as_ref()).await?;
        tx.commit().await?;
        Ok(NodeWithPorts { node, ports })
    }
}

